/** Every ward in a county, offered before a sub-county is chosen. */
export function townsInCounty(county: KenyaCounty): string[] {
  return [...new Set(county.subCounties.flatMap((sub) => sub.wards))].sort((a, b) => a.localeCompare(b));
}

/** Wards of the chosen sub-county, or the whole county when it has none. */
export function townsInSubCounty(county: KenyaCounty, subCounty: string): string[] {
  const sub = county.subCounties.find((s) => s.name === subCounty);
  return sub?.wards.length ? sub.wards : townsInCounty(county);
}
